# Let creat a set

set_01 = {"Pune", "Mumbai", "Indor", "Nagpur", "Jaipur", "Kolkata"}
print(type(set_01))
print(set_01)

# Creating a set from the list
set_02 = set([10, 20, 30, 40, 50, 60])
print(type(set_02))
print(set_02)

# Creating an empty set
set_03 = set()  # the set_03 = {} will create a empty set
print(type(set_03))

# Sets does not allow duplicates and they are also unorderd
set_04 = {10, 20, 30, 10, 40, 50, 60, 40}
print(set_04)
